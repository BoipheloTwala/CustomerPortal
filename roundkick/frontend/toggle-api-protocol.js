function loadEnvFile() {
  if (!fs.existsSync(envPath)) {
    return {};
  }
  
  const envContent = fs.readFileSync(envPath, 'utf8');
  const envVars = {};
  
  envContent.split('\n').forEach(line => {
    line = line.trim();
    if (line && !line.startsWith('#')) {
      const [key, ...valueParts] = line.split('=');
      if (key && valueParts.length > 0) {
        envVars[key.trim()] = valueParts.join('=').trim();
      }
    }
  });
  
  return envVars;
}

function saveEnvFile(envVars) {
  const lines = [];
  
  // Add header comment
  lines.push('# Frontend Environment Configuration');
  lines.push('# Generated by toggle-api-protocol.js script');
  lines.push('');
  
  // Add API configuration section
  lines.push('# API Configuration');
  lines.push(`VITE_API_URL=${envVars.VITE_API_URL}`);
  lines.push(`VITE_API_TIMEOUT=${envVars.VITE_API_TIMEOUT}`);
  lines.push(`VITE_ENABLE_PROTOCOL_FALLBACK=${envVars.VITE_ENABLE_PROTOCOL_FALLBACK}`);
  lines.push(`VITE_MAX_RETRY_ATTEMPTS=${envVars.VITE_MAX_RETRY_ATTEMPTS}`);
  lines.push('');
  
  // Add other configuration sections
  const sections = [
    { title: 'App Configuration', keys: ['VITE_APP_NAME', 'VITE_APP_VERSION', 'VITE_NODE_ENV'] },
    { title: 'Feature Flags', keys: ['VITE_ENABLE_ANALYTICS', 'VITE_ENABLE_DEBUG', 'VITE_ENABLE_DEVTOOLS'] },
    { title: 'Security Configuration', keys: ['VITE_ENABLE_ANTI_MITM', 'VITE_ENABLE_XSS_PROTECTION'] },
    { title: 'CORS Configuration', keys: ['VITE_CORS_ORIGINS'] },
    { title: 'Authentication Configuration', keys: ['VITE_AUTH_TOKEN_KEY', 'VITE_USER_DATA_KEY', 'VITE_SECURITY_TOKEN_KEY', 'VITE_SESSION_TIMEOUT'] },
    { title: 'UI Configuration', keys: ['VITE_THEME', 'VITE_ENABLE_DARK_MODE', 'VITE_DEFAULT_LANGUAGE'] },
    { title: 'Performance Configuration', keys: ['VITE_ENABLE_REQUEST_CACHE', 'VITE_CACHE_DURATION', 'VITE_ENABLE_SERVICE_WORKER'] },
    { title: 'Logging Configuration', keys: ['VITE_ENABLE_CONSOLE_LOGS', 'VITE_LOG_LEVEL', 'VITE_ENABLE_NETWORK_LOGS'] },
    { title: 'Development Tools', keys: ['VITE_ENABLE_REACT_DEVTOOLS', 'VITE_ENABLE_REDUX_DEVTOOLS', 'VITE_HOT_RELOAD'] },
    { title: 'Build Configuration', keys: ['VITE_PUBLIC_PATH', 'VITE_ENABLE_SOURCE_MAPS', 'VITE_ENABLE_BUNDLE_ANALYZER'] },
    { title: 'Testing Configuration', keys: ['VITE_TEST_MODE', 'VITE_ENABLE_MOCK_API', 'VITE_USE_TEST_DATA'] }
  ];
  
  sections.forEach(section => {
    lines.push(`# ${section.title}`);
    section.keys.forEach(key => {
      if (envVars[key] !== undefined) {
        lines.push(`${key}=${envVars[key]}`);
      }
    });
    lines.push('');
  });
  
  fs.writeFileSync(envPath, lines.join('\n'));
}

function toggleAPIProtocol() {
  const args = process.argv.slice(2);
  const command = args[0];
  
  if (!command || !['http', 'https', 'auto', 'status'].includes(command)) {
    console.log(`
API Protocol Toggle Script

Usage: node toggle-api-protocol.js <command>

Commands:
  http     - Use HTTP API endpoint (http://localhost:5000/api)
  https    - Use HTTPS API endpoint (https://localhost:5000/api)
  auto     - Use auto-detection based on current page protocol
  status   - Show current API configuration

Examples:
  node toggle-api-protocol.js http
  node toggle-api-protocol.js https
  node toggle-api-protocol.js auto
  node toggle-api-protocol.js status
`);
    process.exit(1);
  }
  
  const currentEnv = loadEnvFile();
  const envVars = { ...defaultEnvVars, ...currentEnv };
  
  switch (command) {
    case 'http':
      envVars.VITE_API_URL = 'http://localhost:5000/api';
      saveEnvFile(envVars);
      console.log('✅ API endpoint set to HTTP');
      console.log('🌐 Frontend will connect to: http://localhost:5000/api');
      console.log('🔄 Restart your development server to apply changes');
      break;
      
    case 'https':
      envVars.VITE_API_URL = 'https://localhost:5000/api';
      saveEnvFile(envVars);
      console.log('✅ API endpoint set to HTTPS');
      console.log('🔒 Frontend will connect to: https://localhost:5000/api');
      console.log('🔄 Restart your development server to apply changes');
      break;
      
    case 'auto':
      delete envVars.VITE_API_URL;
      saveEnvFile(envVars);
      console.log('✅ API endpoint set to auto-detection');
      console.log('🤖 Frontend will auto-detect protocol based on current page');
      console.log('🔄 Restart your development server to apply changes');
      break;
      
    case 'status':
      console.log('📊 Current API Configuration:');
      console.log(`   VITE_API_URL: ${envVars.VITE_API_URL || 'not set (auto-detection)'}`);
      console.log(`   VITE_API_TIMEOUT: ${envVars.VITE_API_TIMEOUT}ms`);
      console.log(`   VITE_ENABLE_PROTOCOL_FALLBACK: ${envVars.VITE_ENABLE_PROTOCOL_FALLBACK}`);
      console.log(`   VITE_MAX_RETRY_ATTEMPTS: ${envVars.VITE_MAX_RETRY_ATTEMPTS}`);
      
      if (envVars.VITE_API_URL) {
        const isHttps = envVars.VITE_API_URL.startsWith('https://');
        console.log(`   Protocol: ${isHttps ? '🔒 HTTPS' : '🌐 HTTP'}`);
      } else {
        console.log('   Protocol: 🤖 Auto-detection');
      }
      break;
  }
}

toggleAPIProtocol();
